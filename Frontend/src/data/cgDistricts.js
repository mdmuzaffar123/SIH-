// Build a search index: name → key
export const searchIndex = Object.entries(cgData).reduce((acc, [key, val]) => {
  acc[val.name.toLowerCase()] = key;
  // also index villages
  val.solar.topVillages.forEach(v => { acc[v.toLowerCase()] = key; });
  return acc;
}, {});

export const findLocation = (query) => {
  const q = query.toLowerCase().trim();
  // direct match
  if (cgData[q]) return cgData[q];
  // search index
  if (searchIndex[q]) return cgData[searchIndex[q]];
  // partial match
  const partialKey = Object.keys(searchIndex).find(k => k.includes(q) || q.includes(k));
  if (partialKey) return cgData[searchIndex[partialKey]];
  return null;
};

export const allLocations = Object.values(cgData).map(d => d.name);
